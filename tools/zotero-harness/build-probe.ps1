<#
.SYNOPSIS
  Builds the Rust probe crate (probe-wasm) for wasm32-unknown-unknown and copies the
  resulting module into the probe plugin in the three shapes the probe tests:
    probe-plugin/probe_core.wasm                  (fetched via rootURI)
    probe-plugin/content/probe_core.wasm          (fetched via chrome://zfprobe/content/)
    probe-plugin/content/probe_core.wasm.b64.js   (base64 embedded in a script)
  Respects CARGO_TARGET_DIR / ~/.cargo/config.toml by asking cargo for the target dir.
#>
[CmdletBinding()]
param(
    [switch]$Offline
)
$ErrorActionPreference = 'Stop'
$here   = Split-Path -Parent $MyInvocation.MyCommand.Path
$crate  = Join-Path $here 'probe-wasm'
$plugin = Join-Path $here 'probe-plugin'

$cargoArgs = @('build', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', (Join-Path $crate 'Cargo.toml'))
if ($Offline) { $cargoArgs += '--offline' }
& cargo @cargoArgs
if ($LASTEXITCODE -ne 0) { throw "cargo build failed ($LASTEXITCODE)" }

$meta = & cargo metadata --format-version 1 --no-deps --manifest-path (Join-Path $crate 'Cargo.toml') | ConvertFrom-Json
$wasm = Join-Path $meta.target_directory 'wasm32-unknown-unknown\release\probe_core.wasm'
if (-not (Test-Path $wasm)) { throw "wasm not found at $wasm" }

New-Item -ItemType Directory -Force (Join-Path $plugin 'content') | Out-Null
Copy-Item $wasm (Join-Path $plugin 'probe_core.wasm') -Force
Copy-Item $wasm (Join-Path $plugin 'content\probe_core.wasm') -Force

$bytes = [IO.File]::ReadAllBytes($wasm)
$b64 = [Convert]::ToBase64String($bytes)
$sha = (Get-FileHash $wasm -Algorithm SHA256).Hash.ToLower()
$js = "/* generated by build-probe.ps1 - do not edit */`nvar ZF_PROBE_WASM_B64 = `"$b64`";`nvar ZF_PROBE_WASM_SHA256 = `"$sha`";`n"
[IO.File]::WriteAllText((Join-Path $plugin 'content\probe_core.wasm.b64.js'), $js, [Text.UTF8Encoding]::new($false))

Write-Host ("probe_core.wasm: {0} bytes, sha256 {1}" -f $bytes.Length, $sha)

# wasm-bindgen variant (crate pins wasm-bindgen to the installed CLI version)
$wbgCrate = Join-Path $here 'probe-wasm-bindgen'
if (Get-Command wasm-bindgen -ErrorAction SilentlyContinue) {
    $wbgArgs = @('build', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', (Join-Path $wbgCrate 'Cargo.toml'))
    if ($Offline) { $wbgArgs += '--offline' }
    & cargo @wbgArgs
    if ($LASTEXITCODE -ne 0) { throw "cargo build (wasm-bindgen crate) failed ($LASTEXITCODE)" }
    $wbgWasm = Join-Path $meta.target_directory 'wasm32-unknown-unknown\release\probe_wbg.wasm'
    foreach ($t in @('web', 'no-modules')) {
        $dir = Join-Path $plugin ('content\wbg-' + $(if ($t -eq 'web') { 'web' } else { 'nomod' }))
        & wasm-bindgen --target $t --out-dir $dir $wbgWasm
        if ($LASTEXITCODE -ne 0) { throw "wasm-bindgen --target $t failed" }
    }
    # second copy of the ES-module glue under a different URL (= separate module instance)
    Copy-Item (Join-Path $plugin 'content\wbg-web\probe_wbg.js') (Join-Path $plugin 'content\wbg-web\probe_wbg.mjs') -Force
    Write-Host ("probe_wbg_bg.wasm: {0} bytes" -f (Get-Item (Join-Path $plugin 'content\wbg-web\probe_wbg_bg.wasm')).Length)
} else {
    Write-Warning 'wasm-bindgen CLI not found; skipping the wasm-bindgen variant'
}

# Pack the plugin as an XPI (zip with forward-slash entry names, manifest.json at the root)
$outDir = Join-Path $here 'out'
New-Item -ItemType Directory -Force $outDir | Out-Null
$xpi = Join-Path $outDir 'probe@zotero-fulltext.local.xpi'
Remove-Item -Force -ErrorAction SilentlyContinue $xpi
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::Open($xpi, [IO.Compression.ZipArchiveMode]::Create)
try {
    Get-ChildItem $plugin -Recurse -File | ForEach-Object {
        $rel = $_.FullName.Substring($plugin.Length + 1).Replace('\', '/')
        [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $_.FullName, $rel, [IO.Compression.CompressionLevel]::Optimal)
    }
} finally { $zip.Dispose() }
Write-Host ("packed {0} ({1} bytes)" -f $xpi, (Get-Item $xpi).Length)
